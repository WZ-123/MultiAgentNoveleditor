'use strict';

const { constants, promises: fs } = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const { paths, generateId } = require('./paths');
const { writeJson } = require('./jsonStore');

let mutationQueue = Promise.resolve();
function mutate(operation) {
  const next = mutationQueue.then(operation);
  mutationQueue = next.catch(() => {});
  return next;
}

function securityError(message, code = 'feedback_path_invalid') {
  return Object.assign(new Error(message), { code });
}

function validateFeedbackId(feedbackId) {
  // Includes IDs generated by every prior version, plus existing safe caller IDs.
  if (typeof feedbackId !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,127}$/.test(feedbackId) || /^(?:index|con|prn|aux|nul|com[1-9]|lpt[1-9])$/i.test(feedbackId)) {
    throw securityError('反馈 ID 格式无效', 'feedback_id_invalid');
  }
  return feedbackId;
}

function childPath(name) {
  const root = path.resolve(outboxDir());
  const file = path.resolve(root, name);
  if (path.dirname(file) !== root) throw securityError('反馈路径超出存储目录');
  return file;
}

async function ensureFeedbackOutbox() {
  await fs.mkdir(outboxDir(), { recursive: true });
  const stat = await fs.lstat(outboxDir());
  if (!stat.isDirectory() || stat.isSymbolicLink()) throw securityError('反馈存储目录不能是符号链接');
}

async function assertRegularFile(file) {
  await ensureFeedbackOutbox();
  try {
    const stat = await fs.lstat(file);
    if (!stat.isFile() || stat.isSymbolicLink()) throw securityError('反馈文件不能是符号链接或特殊文件');
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
}

async function readFile(file) {
  await assertRegularFile(file);
  const handle = await fs.open(file, constants.O_RDONLY | (constants.O_NOFOLLOW || 0));
  try {
    if (!(await handle.stat()).isFile()) throw securityError('反馈文件不是普通文件');
    return await handle.readFile();
  } finally { await handle.close(); }
}

async function readJson(file, fallback = null) {
  try { return JSON.parse((await readFile(file)).toString('utf8')); }
  catch (error) { if (error.code === 'ENOENT') return fallback; throw error; }
}

async function safeWriteJson(file, value) {
  await assertRegularFile(file);
  await writeJson(file, value, { mode: 0o600 });
}

function outboxDir() {
  return paths().feedbackOutbox;
}

function indexPath() {
  return childPath('index.json');
}

function feedbackPath(feedbackId) {
  return childPath(`${validateFeedbackId(feedbackId)}.json`);
}

function attachmentPath(feedbackId, fileName) {
  validateFeedbackId(feedbackId);
  if (typeof fileName !== 'string' || !/^[a-zA-Z0-9._-]{1,128}$/.test(fileName) || fileName === '.' || fileName === '..') throw securityError('反馈附件名称无效');
  return childPath(`${feedbackId}-${fileName}`);
}

async function readIndex() {
  return readJson(indexPath(), { items: [] });
}

async function writeIndex(index) {
  await safeWriteJson(indexPath(), index);
}

function enrichPayload(payload) {
  const next = payload && typeof payload === 'object' ? { ...payload } : {};
  const environment = next.environment && typeof next.environment === 'object' ? { ...next.environment } : {};
  if (!environment.appVersion) {
    try {
      environment.appVersion = require(path.join(__dirname, '../../../package.json')).version || '';
    } catch {
      environment.appVersion = '';
    }
  }
  next.environment = environment;
  return next;
}

function sanitizeFileName(fileName) {
  const name = String(fileName || 'attachment.bin').replace(/[^a-zA-Z0-9._-]/g, '_').slice(0, 110);
  return name === '.' || name === '..' ? 'attachment.bin' : name;
}

async function writeAttachments(feedbackId, attachments, createdFiles) {
  const normalized = Array.isArray(attachments) ? attachments : [];
  const saved = [];
  const usedNames = new Set();
  for (const attachment of normalized) {
    const buffer = attachment?.data;
    if (!Buffer.isBuffer(buffer) || !buffer.length) continue;
    const baseName = sanitizeFileName(attachment.fileName || `${attachment.kind || 'attachment'}.bin`);
    let fileName = baseName;
    for (let suffix = 1; usedNames.has(fileName); suffix++) fileName = `${suffix}-${baseName}`;
    usedNames.add(fileName);
    const filePath = attachmentPath(feedbackId, fileName);
    await fs.writeFile(filePath, buffer, { flag: 'wx', mode: 0o600 });
    createdFiles.push(filePath);
    saved.push({
      kind: attachment.kind || 'attachment',
      label: attachment.label || fileName,
      mimeType: attachment.mimeType || 'application/octet-stream',
      fileName,
      localPath: filePath,
      size: buffer.length,
      createdAt: new Date().toISOString(),
    });
  }
  return saved;
}

async function submitFeedbackRecorded(payload, options = {}) {
  const enriched = enrichPayload(payload);
  const feedbackId = enriched.feedbackId == null || enriched.feedbackId === '' ? generateId('fb') : validateFeedbackId(enriched.feedbackId);
  const file = feedbackPath(feedbackId);
  await assertRegularFile(indexPath());
  try {
    await fs.lstat(file);
    throw securityError('反馈 ID 已存在，请勿重复提交', 'feedback_id_duplicate');
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const stagedFile = childPath(`.record-${crypto.randomUUID()}.tmp`);
  let published = false;
  const createdFiles = [];
  try {
    const createdAt = enriched.createdAt || new Date().toISOString();
    const attachments = await writeAttachments(feedbackId, options.attachments, createdFiles);
    const endpointProfile = options.endpointProfile || 'dev';
    const record = {
      feedbackId,
      createdAt,
      status: 'pending',
      transport: 'local-outbox',
      syncStatus: 'pending',
      retryCount: 0,
      lastSendAttemptAt: null,
      lastSendSucceededAt: null,
      nextRetryAt: null,
      lastError: null,
      lastErrorCode: null,
      remoteRecordId: null,
      remoteTableId: null,
      remoteAttachmentTokens: [],
      endpointProfile,
      transportMeta: null,
      payload: {
        ...enriched,
        feedbackId,
        createdAt,
        attachments,
      },
    };
    await safeWriteJson(stagedFile, record);
    // Publish a complete JSON file atomically without replacing an existing ID.
    try { await fs.link(stagedFile, file); }
    catch (error) { if (error.code === 'EEXIST') throw securityError('反馈 ID 已存在，请勿重复提交', 'feedback_id_duplicate'); throw error; }
    published = true;
    await fs.unlink(stagedFile);

    const index = await readIndex();
    const items = Array.isArray(index.items) ? index.items.filter((item) => item.feedbackId !== feedbackId) : [];
    items.unshift({
      feedbackId,
      createdAt,
      status: 'pending',
      syncStatus: 'pending',
      issueTitle: record.payload?.userInput?.issueTitle || '未命名反馈',
      feedbackMode: record.payload?.userInput?.feedbackMode || 'opinion-only',
    });
    await writeIndex({ items });

    return {
      feedbackId,
      createdAt,
      status: 'pending',
      syncStatus: 'pending',
      attachments,
      savedTo: feedbackPath(feedbackId),
    };
  } catch (error) {
    await Promise.all([stagedFile, ...(published ? [file] : []), ...createdFiles].map(target => fs.unlink(target).catch(() => {})));
    throw error;
  }
}

function submitFeedback(payload, options = {}) {
  return mutate(() => submitFeedbackRecorded(payload, options));
}

async function readRecord(feedbackId) {
  const record = await readJson(feedbackPath(feedbackId), null);
  if (record && record.feedbackId !== feedbackId) throw securityError('反馈记录身份与文件名不一致');
  return record;
}

async function getRecord(feedbackId) {
  validateFeedbackId(feedbackId);
  await mutationQueue;
  return readRecord(feedbackId);
}

async function updateSyncMetaRecorded(feedbackId, patch) {
  const file = feedbackPath(feedbackId);
  const record = await readRecord(feedbackId);
  if (!record) return null;

  const allowed = [
    'syncStatus',
    'retryCount',
    'lastSendAttemptAt',
    'lastSendSucceededAt',
    'nextRetryAt',
    'lastError',
    'lastErrorCode',
    'remoteRecordId',
    'remoteTableId',
    'remoteAttachmentTokens',
    'endpointProfile',
    'transportMeta',
  ];
  const next = { ...record };
  for (const key of allowed) {
    if (key in patch) next[key] = patch[key];
  }
  await safeWriteJson(file, next);

  // Update index summary if syncStatus changed
  if ('syncStatus' in patch) {
    const index = await readIndex();
    const items = Array.isArray(index.items) ? index.items : [];
    const idx = items.findIndex((item) => item.feedbackId === feedbackId);
    if (idx >= 0) {
      items[idx] = { ...items[idx], syncStatus: patch.syncStatus };
      await writeIndex({ items });
    }
  }

  return next;
}

function updateSyncMeta(feedbackId, patch) {
  return mutate(() => updateSyncMetaRecorded(feedbackId, patch));
}

async function listRecords() {
  await ensureFeedbackOutbox();
  const names = await fs.readdir(outboxDir());
  const records = [];
  for (const name of names) {
    if (!name.endsWith('.json') || name === 'index.json') continue;
    try {
      const record = await readRecord(name.slice(0, -5));
      if (record) records.push(record);
    } catch (error) {
      // A malformed or unsafe record must not prevent valid legacy records syncing.
      if (!['feedback_id_invalid', 'feedback_path_invalid', 'ELOOP'].includes(error.code) && !(error instanceof SyntaxError)) throw error;
    }
  }
  return records;
}

async function listPendingForSync() {
  await mutationQueue;
  const now = new Date().toISOString();
  const pending = (await listRecords()).filter(record => {
    const status = record.syncStatus;
    return (status === 'pending' || status === 'retryable_failed') && (!record.nextRetryAt || record.nextRetryAt <= now);
  });
  pending.sort((a, b) => (a.createdAt || '').localeCompare(b.createdAt || ''));
  return pending;
}

async function listAllRecords() {
  await mutationQueue;
  const records = await listRecords();
  records.sort((a, b) => (b.createdAt || '').localeCompare(a.createdAt || ''));
  return records;
}

async function recoverStuckSyncing() {
  const records = await listAllRecords();
  let recovered = 0;
  for (const record of records) {
    if (record && record.syncStatus === 'syncing') {
      await updateSyncMeta(record.feedbackId, { syncStatus: 'pending' });
      recovered += 1;
    }
  }
  return recovered;
}

async function readAttachment(feedbackId, attachment) {
  const file = attachmentPath(feedbackId, attachment?.fileName);
  if (typeof attachment?.localPath !== 'string' || path.resolve(attachment.localPath) !== file) throw securityError('反馈附件路径与记录不一致');
  return readFile(file);
}

module.exports = {
  submitFeedback,
  getRecord,
  updateSyncMeta,
  listPendingForSync,
  listAllRecords,
  recoverStuckSyncing,
  feedbackPath,
  attachmentPath,
  outboxDir,
  readIndex,
  validateFeedbackId,
  readAttachment,
};
